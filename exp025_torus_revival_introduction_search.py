REVIVAL_KS = sorted([2, 3, 4, 5, 6, 8, 10])

# Set of all revival periods for each k
def get_revival_periods(k):
    """Get all N where U_k^N = I for some 0<rho<1."""
    if k not in ONE_D_REVIVALS:
        return set()
    return set(N for _, _, N in ONE_D_REVIVALS[k])

# Pre-compute all revival periods
REVIVAL_PERIODS = {k: get_revival_periods(k) for k in REVIVAL_KS}


