def find_common_periods(k, m):
    """
    Find common revival periods between k-cycle and m-cycle.

    Returns:
        Set of N where both U_k^N = I and U_m^N = I
    """
    periods_k = REVIVAL_PERIODS.get(k, set())
    periods_m = REVIVAL_PERIODS.get(m, set())
    return periods_k & periods_m


def classify_torus(k, m):
    """
    Classify whether a k x m torus has separable quantum walk revivals.

    Returns:
        dict with classification details
    """
    if k not in REVIVAL_KS or m not in REVIVAL_KS:
        return {
            'has_revival': False,
            'reason': f'k={k} or m={m} has no 1D revivals',
            'common_periods': set()
        }

    common_periods = find_common_periods(k, m)

    if common_periods:
        return {
            'has_revival': True,
            'min_N': min(common_periods),
            'all_periods': sorted(common_periods),
            'reason': f'Both have revivals with common period N={min(common_periods)}'
        }
    else:
        periods_k = REVIVAL_PERIODS[k]
        periods_m = REVIVAL_PERIODS[m]
        return {
            'has_revival': False,
            'reason': f'k={k} periods {sorted(periods_k)[:5]}..., m={m} periods {sorted(periods_m)[:5]}... no overlap',
            'common_periods': set()
        }


