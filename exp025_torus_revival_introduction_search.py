def plot_torus_probability_evolution(k, m, rho_x, delta_x, rho_y, delta_y,
                                      max_steps, N_revival=None, save_path=None):
    """
    Simulate and visualize separable quantum walk on a torus.

    This creates a 3D visualization of probability distribution over time.
    """
    from scipy.linalg import kron

    # Build 1D operators
    U_x = construct_1D_operator(k, rho_x, delta_x)
    U_y = construct_1D_operator(m, rho_y, delta_y)

    # Build 2D separable operator (Kronecker product)
    U_2d = kron(U_x, U_y)

    # Initial state: |0,0,up,up>
    psi = np.zeros((2*k, 2*m), dtype=complex)
    psi[0, 0] = 1.0  # Position (0,0), coin (up,up)
    psi = psi.flatten()

    # Simulate
    probabilities = []
    for step in range(max_steps + 1):
        # Compute position probabilities (sum over coin states)
        prob_2d = np.abs(psi.reshape(2*k, 2*m))**2
        pos_prob = prob_2d.reshape(k, 2, m, 2).sum(axis=(1, 3))
        probabilities.append(pos_prob)

        if step < max_steps:
            psi = U_2d @ psi

    # Create visualization (simplified - a full 3D animation would be more complex)
    fig, axes = plt.subplots(2, 3, figsize=(15, 10))
    axes = axes.flatten()

    steps_to_show = [0, N_revival//4 if N_revival else max_steps//4,
                     N_revival//2 if N_revival else max_steps//2,
                     (3*N_revival)//4 if N_revival else (3*max_steps)//4,
                     N_revival if N_revival else max_steps,
                     max_steps]
    steps_to_show = [s for s in steps_to_show if s <= max_steps]

    for idx, step in enumerate(steps_to_show[:6]):
        ax = axes[idx]
        im = ax.imshow(probabilities[step], cmap='hot', interpolation='bilinear', origin='lower')
        ax.set_title(f'Step {step}')
        ax.set_xlabel('y')
        ax.set_ylabel('x')

    plt.suptitle(f'Probability Evolution on {k}×{m} Torus\n'
                 f'ρ_x={rho_x:.3f}, δ_x={delta_x/np.pi:.2f}π, '
                 f'ρ_y={rho_y:.3f}, δ_y={delta_y/np.pi:.2f}π',
                 fontsize=12)
    plt.tight_layout()

    if save_path:
        plt.savefig(save_path, dpi=300, bbox_inches='tight')
        print(f"Saved: {save_path}")
    plt.close()

    return probabilities


def construct_1D_operator(k, rho, delta):
    """Construct 1D quantum walk operator on k-cycle."""
    # Coin operator
    C = np.array([
        [np.sqrt(rho), np.sqrt(1-rho) * np.exp(1j * delta)],
        [np.sqrt(1-rho), -np.sqrt(rho) * np.exp(1j * delta)]
    ])

    # Shift operator
    S = np.zeros((2*k, 2*k), dtype=complex)
    for i in range(k):
        # up -> left
        S[2*((i-1)%k) + 0, 2*i + 0] = 1
        # down -> right
        S[2*((i+1)%k) + 1, 2*i + 1] = 1

    # Combined operator
    I_k = np.eye(k)
    U = S @ np.kron(I_k, C)

    return U


