def plot_torus_classification_matrix(revival_matrix, max_k=10, save_path=None):
    """
    Create a heatmap visualization of the torus classification.
    """
    import matplotlib.pyplot as plt
    from matplotlib.colors import LinearSegmentedColormap

    # Create matrix
    matrix = np.zeros((max_k + 1, max_k + 1))

    for k in range(2, max_k + 1):
        for m in range(2, max_k + 1):
            if (k, m) in revival_matrix:
                matrix[k, m] = revival_matrix[(k, m)]
            else:
                matrix[k, m] = 0

    fig, ax = plt.subplots(figsize=(12, 10))

    # Custom colormap for N values
    colors = ['#ffffff', '#fee5d9', '#fcae91', '#fb6a4a', '#cb181d', '#67000d']
    cmap = LinearSegmentedColormap.from_list('revival_heatmap', colors, N=100)

    # Plot (excluding k=1, m=1)
    im = ax.imshow(matrix[1:, 1:], origin='lower', cmap=cmap,
                   interpolation='nearest', aspect='auto',
                   vmin=0, vmax=120)

    # Add text annotations
    for k in range(2, max_k + 1):
        for m in range(2, max_k + 1):
            val = matrix[k, m]
            if val > 0:
                ax.text(m-2, k-2, f'{int(val)}', ha='center', va='center',
                       color='white', fontsize=9, fontweight='bold')
            elif k in [2,3,4,5,6,8,10] and m in [2,3,4,5,6,8,10]:
                ax.text(m-2, k-2, '✗', ha='center', va='center',
                       color='gray', fontsize=14)

    # Formatting
    ax.set_xticks(range(max_k - 1))
    ax.set_xticklabels(range(2, max_k + 1))
    ax.set_yticks(range(max_k - 1))
    ax.set_yticklabels(range(2, max_k + 1))
    ax.set_xlabel('m (y-dimension)', fontsize=12)
    ax.set_ylabel('k (x-dimension)', fontsize=12)
    ax.set_title('Separable Quantum Walks on Tori: Minimum Revival Period N', fontsize=14)

    # Colorbar
    cbar = plt.colorbar(im, ax=ax)
    cbar.set_label('Minimum Revival Period N', fontsize=10)

    plt.tight_layout()

    if save_path:
        plt.savefig(save_path, dpi=300, bbox_inches='tight')
        print(f"\nSaved: {save_path}")
    plt.close()


