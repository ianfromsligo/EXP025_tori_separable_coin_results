def find_torus_revivals(k_values, max_N=120, use_known=True):
    """
    Find all torus revivals by matching 1D revival periods.

    Parameters:
    - k_values: list of cycle lengths to consider
    - max_N: maximum revival period
    - use_known: use known 1D revival data

    Returns:
    - dictionary of torus -> list of (N, params_x, params_y)
    """
    print("\n" + "=" * 80)
    print("FINDING TORUS REVIVALS BY MATCHING 1D REVIVAL PERIODS")
    print("=" * 80)

    # Get 1D revivals for all k
    one_d_data = {}
    for k in k_values:
        one_d_data[k] = get_1d_revivals(k, use_known=use_known)
        print(f"k={k}: {len(one_d_data[k])} revival parameter sets")

    # Group by N for efficient matching
    revivals_by_N = defaultdict(lambda: defaultdict(list))

    for k, revivals in one_d_data.items():
        for rho, delta, N in revivals:
            if N <= max_N:
                revivals_by_N[N][k].append((rho, delta))

    # Find compatible torus pairs
    torus_revivals = defaultdict(list)

    for N in sorted(revivals_by_N.keys()):
        ks_with_revival = list(revivals_by_N[N].keys())

        # All pairs (including same k)
        for i, k in enumerate(ks_with_revival):
            for m in ks_with_revival[i:]:  # symmetric, only upper triangle
                # Get all parameter combinations
                params_k = revivals_by_N[N][k]
                params_m = revivals_by_N[N][m]

                for rho_k, delta_k in params_k:
                    for rho_m, delta_m in params_m:
                        torus_revivals[(k, m)].append({
                            'N': N,
                            'rho_x': rho_k, 'delta_x': delta_k,
                            'rho_y': rho_m, 'delta_y': delta_m
                        })

                        # Also add symmetric case
                        if k != m:
                            torus_revivals[(m, k)].append({
                                'N': N,
                                'rho_x': rho_m, 'delta_x': delta_m,
                                'rho_y': rho_k, 'delta_y': delta_k
                            })

    return torus_revivals


