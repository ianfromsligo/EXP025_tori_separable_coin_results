def construct_U_k(k, rho, delta):
    """
    Construct 1D quantum walk operator U_k on a k-cycle.

    Parameters:
    - k: cycle length
    - rho: coin parameter (0 <= rho <= 1)
    - delta: alpha + beta (phase sum)

    Returns:
    - U: 2k x 2k unitary matrix
    """
    # Coin operator (using beta=0, alpha=delta)
    C = np.array([
        [np.sqrt(rho), np.sqrt(1-rho) * np.exp(1j * delta)],
        [np.sqrt(1-rho), -np.sqrt(rho) * np.exp(1j * delta)]
    ], dtype=complex)

    # Initialize shift operator
    S = np.zeros((2*k, 2*k), dtype=complex)

    for i in range(k):
        # Spin up (0) moves left
        S[2*((i-1)%k) + 0, 2*i + 0] = 1.0
        # Spin down (1) moves right
        S[2*((i+1)%k) + 1, 2*i + 1] = 1.0

    # Combine: U = S * (I_k ⊗ C)
    I_k = np.eye(k)
    U = S @ np.kron(I_k, C)

    return U


def verify_1d_revival(k, rho, delta, N, tol=1e-8):
    """
    Verify if U_k^N = I_{2k} for given parameters.

    Returns:
    - is_revival: boolean
    - diff_norm: numerical difference
    """
    U = construct_U_k(k, rho, delta)

    # Compute U^N using repeated squaring for stability
    U_power = np.linalg.matrix_power(U, N)

    # Check if approximately identity
    I = np.eye(2*k, dtype=complex)
    diff = np.linalg.norm(U_power - I)

    if diff < tol:
        # Also verify eigenvalues are N-th roots of unity
        evals = np.linalg.eigvals(U)
        max_eig_error = max(abs(ev**N - 1) for ev in evals)
        return max_eig_error < tol, diff, max_eig_error

    return False, diff, None


def search_1d_revivals(k, max_N=120, rho_precision=0.01, delta_precision=np.pi/36):
    """
    Search for all revival parameters for a given k.

    Parameters:
    - k: cycle length
    - max_N: maximum period to search
    - rho_precision: step size for rho scan
    - delta_precision: step size for delta scan (radians)

    Returns:
    - list of (rho, delta, N) tuples
    """
    print(f"  Searching k={k}...")

    revivals = []

    # Special case: k=2 has infinite family at delta=0
    if k == 2:
        for rho in np.arange(0.1, 1.0, rho_precision):
            result = verify_1d_revival(2, rho, 0, 2)
            if result[0]:
                revivals.append((rho, 0, 2))
        # Also check delta=pi? (Should work too)
        for rho in np.arange(0.1, 1.0, rho_precision):
            result = verify_1d_revival(2, rho, np.pi, 2)
            if result[0]:
                revivals.append((rho, np.pi, 2))

    # Search over parameter space
    rho_values = np.arange(0.01, 0.99, rho_precision)
    delta_values = np.arange(0, 2*np.pi, delta_precision)

    # For each N, check if any parameters work
    for N in range(2, max_N + 1):
        for rho in rho_values:
            for delta in delta_values:
                # Quick skip: eigenvalues must be N-th roots
                # This is a necessary condition we can check quickly
                is_revival, diff, _ = verify_1d_revival(k, rho, delta, N)

                if is_revival:
                    revivals.append((round(rho, 4), round(delta, 4), N))
                    print(f"    Found: ρ={rho:.4f}, δ={delta/np.pi:.2f}π, N={N}")

    return revivals


