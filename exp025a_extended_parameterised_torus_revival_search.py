def verify_torus_revival(k, m, rho_x, delta_x, rho_y, delta_y, N, tol=1e-8):
    """
    Verify that a specific torus revival works.

    For a separable torus, U_torus = U_k ⊗ U_m.
    So U_torus^N = I iff U_k^N = I AND U_m^N = I.
    """
    print(f"\nVerifying {k}×{m} torus with N={N}...")
    print(f"  x-direction: ρ={rho_x:.6f}, δ={delta_x/np.pi:.3f}π")
    print(f"  y-direction: ρ={rho_y:.6f}, δ={delta_y/np.pi:.3f}π")

    # Verify x-direction
    result_x = verify_1d_revival(k, rho_x, delta_x, N, tol)
    # Verify y-direction
    result_y = verify_1d_revival(m, rho_y, delta_y, N, tol)

    if result_x[0] and result_y[0]:
        print(f"  ✓ VERIFIED: Both dimensions revive at N={N}")
        return True
    else:
        print(f"  ✗ FAILED: x: {result_x[1]:.2e}, y: {result_y[1]:.2e}")
        return False


