def hunt_exhaustive_revivals():
    """Hunts for 2D revivals by crossing all 1D parameters, including mixed-deltas."""

    knowledge_base = get_exhaustive_1d_knowledge()
    # Mirror identical sets (k=6 shares k=3 solutions; k=10 shares k=5)
    knowledge_base[6] = knowledge_base[3]
    knowledge_base[10] = knowledge_base[5]

    print(f"{'Torus (N x M)':<14} | {'ρ_x':<8} | {'δ_x':<6} | {'ρ_y':<8} | {'δ_y':<6} | {'Steps (N)':<10} | {'Fidelity'}")
    print("-" * 80)

    # We use a set to avoid printing visually identical symmetrical torus permutations
    found_configurations = set()

    for N in range(3, 11):
        for M in range(N, 11):
            if N not in knowledge_base or M not in knowledge_base:
                continue

            for rho_x, delta_x, steps_x in knowledge_base[N]:
                for rho_y, delta_y, steps_y in knowledge_base[M]:

                    target_2d_steps = math.lcm(steps_x, steps_y)

                    # Create a unique hash for this configuration to prevent duplicate output
                    config_hash = f"{N}x{M}_{rho_x:.3f}_{delta_x:.3f}_{rho_y:.3f}_{delta_y:.3f}_{target_2d_steps}"
                    if config_hash in found_configurations:
                        continue

                    fidelity = simulate_walk(N, M, rho_x, delta_x, rho_y, delta_y, target_2d_steps)

                    if fidelity > 0.99:
                        found_configurations.add(config_hash)

                        # Format delta output nicely
                        dx_str = f"{delta_x/np.pi:.2f}π" if delta_x != 0 else "0"
                        dy_str = f"{delta_y/np.pi:.2f}π" if delta_y != 0 else "0"

                        print(f"{N} x {M:<10} | {rho_x:<8.4f} | {dx_str:<6} | {rho_y:<8.4f} | {dy_str:<6} | {target_2d_steps:<10} | {fidelity:.6f}")

if __name__ == "__main__":
    hunt_exhaustive_revivals()