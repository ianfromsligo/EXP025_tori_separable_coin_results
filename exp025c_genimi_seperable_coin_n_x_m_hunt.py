import numpy as np
import math

def create_1d_coin(rho, delta):
    """
    Creates the exact 1D coin operator from Dukes Eq. (1).
    Parameterized by probability rho and phase delta = alpha + beta.
    For simplicity, we assign alpha = delta and beta = 0.
    """
    a = np.sqrt(rho)
    b = np.sqrt(1 - rho) * np.exp(1j * delta)
    c = np.sqrt(1 - rho)
    d = -np.sqrt(rho) * np.exp(1j * delta)

    return np.array([[a, b],
                     [c, d]], dtype=complex)

def create_2d_coin(rho_x, delta_x, rho_y, delta_y):
    """Creates the 4x4 separable 2D coin via tensor product."""
    C_x = create_1d_coin(rho_x, delta_x)
    C_y = create_1d_coin(rho_y, delta_y)
    return np.kron(C_x, C_y)

def shift_operator(state, N, M):
    """Applies a true separable 2D shift (simultaneous diagonal stepping)."""
    next_state = np.zeros_like(state)

    # State 0: X Left (-1), Y Down (-1)
    next_state[:, :, 0] = np.roll(np.roll(state[:, :, 0], shift=-1, axis=0), shift=-1, axis=1)
    # State 1: X Left (-1), Y Up (+1)
    next_state[:, :, 1] = np.roll(np.roll(state[:, :, 1], shift=-1, axis=0), shift=1, axis=1)
    # State 2: X Right (+1), Y Down (-1)
    next_state[:, :, 2] = np.roll(np.roll(state[:, :, 2], shift=1, axis=0), shift=-1, axis=1)
    # State 3: X Right (+1), Y Up (+1)
    next_state[:, :, 3] = np.roll(np.roll(state[:, :, 3], shift=1, axis=0), shift=1, axis=1)

    return next_state

def simulate_walk(N, M, rho_x, delta_x, rho_y, delta_y, target_steps):
    """Evolves the system and returns the fidelity at the target step."""
    C = create_2d_coin(rho_x, delta_x, rho_y, delta_y)

    # Localized symmetric initial state
    state = np.zeros((N, M, 4), dtype=complex)
    state[0, 0, 0] = 0.5
    state[0, 0, 1] = 0.5j
    state[0, 0, 2] = 0.5
    state[0, 0, 3] = -0.5j

    initial_vector = state.flatten()

    for _ in range(target_steps):
        # Apply Coin
        flat_spatial = state.reshape(-1, 4)
        coined_spatial = np.dot(flat_spatial, C.T)
        state = coined_spatial.reshape(N, M, 4)

        # Apply Shift
        state = shift_operator(state, N, M)

    current_vector = state.flatten()
    fidelity = np.abs(np.vdot(initial_vector, current_vector))**2
    return fidelity

